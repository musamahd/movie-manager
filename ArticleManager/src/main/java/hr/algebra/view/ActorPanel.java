    private void initDragNDrop() {
        
        lsAllActors.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        lsAllActors.setDragEnabled(true);
        lsAllActors.setTransferHandler(new ExportHandler());
        
        lsActors.setDropMode(DropMode.ON);
        lsActors.setTransferHandler(new ImportHandler());
        
        
    }

    @Override
    public boolean addActor(Actor actor) {
        if (allActors.add(actor)) {
            loadAllActorsModel();
        
            return true;
           
        }
        return false;
        
    }

    private void loadOrParseMovies() {
         try {
            movieRepository = RepositoryFactory.getMovieRepository();
            
            List<Movie> dbMovies = movieRepository.selectMovies();
            if (dbMovies.isEmpty()) {
                List<Movie> parsedMovies = MovieParser.parse();
                movieRepository.createMovies(parsedMovies);
                dbMovies = parsedMovies;
            }
            
            movies.clear();
            movies.addAll(dbMovies);
            loadMoviesModel();
        } catch (Exception ex) {
                    Logger.getLogger(GenrePanel.class.getName()).log(Level.SEVERE, null, ex);
                     JOptionPane.showMessageDialog(this, "Failed to load or parse movies.");
        }
    }

    private void loadActorsFromDatabase() {
        try {
        List<Actor> dbActors = actorRepository.selectActors();
        allActors.clear();
        allActors.addAll(dbActors);
        loadAllActorsModel();
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Failed to load actors from database.");
    }
    }

