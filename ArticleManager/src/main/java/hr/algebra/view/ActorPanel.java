    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
       Movie selectedMovie = lsMovies.getSelectedValue();
    Actor selectedActor = lsAllActors.getSelectedValue();

    if (selectedMovie == null || selectedActor == null) {
        JOptionPane.showMessageDialog(this, "Please select both a movie and an actor.");
        return;
    }

    try {
        movieRepository.addActorToMovie(selectedMovie.getId(), selectedActor.getId());
       
        JOptionPane.showMessageDialog(this, "Actor successfully added to movie!");
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Failed to add actor to movie.");
    }
    }//GEN-LAST:event_btnAddActionPerformed

