    private class ImportHandler extends TransferHandler {

        @Override
        public boolean canImport(TransferSupport support) {
            return support.isDataFlavorSupported(ActorTransferable.ACTOR_FLAVOR); // Generated from nbfs://nbhost/SystemFileSystem/Templates/Classes/Code/OverriddenMethodBody
        }

        @Override
        public boolean importData(TransferSupport support) {
            
            try {
                Transferable transferable=support.getTransferable();
                
                Actor data=(Actor)transferable.getTransferData(ActorTransferable.ACTOR_FLAVOR);
                
                if (actors.add(data)) {
                    loadActorsModel();
                    return true;
                }
                
                
               
            } catch (UnsupportedFlavorException | IOException ex) {
                Logger.getLogger(ActorPanel.class.getName()).log(Level.SEVERE, null, ex);
            }
             return false;
        
            }
    }
