    private class ImportHandler extends TransferHandler {

        @Override
        public boolean canImport(TransferSupport support) {
            return  support.isDataFlavorSupported(GenreTransferable.GENRE_FLAVOR);
        }

        @Override
        public boolean importData(TransferSupport support) {
            try {
                Transferable transferable=support.getTransferable();
                
                Genre data=(Genre)transferable.getTransferData(GenreTransferable.GENRE_FLAVOR);
                
                if (genres.add(data)) {
                    loadGenresModel();
                    return true;
                    
                }
                
            } catch (UnsupportedFlavorException | IOException ex) {
                Logger.getLogger(GenrePanel.class.getName()).log(Level.SEVERE, null, ex);
            }
            return false;
        }
        

        
    }
