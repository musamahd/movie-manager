    @Override
    public boolean addGenre(Genre genre) {
        if (allGenres.add(genre)) {
            loadAllGenresModel();

            return true;
        }
        return false;
    }

    private void initDragNDrop() {
        lsAllGenres.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        lsAllGenres.setDragEnabled(true);
        lsAllGenres.setTransferHandler(new ExportHandler());
        
        
        lsGenres.setDropMode(DropMode.ON);
        lsGenres.setTransferHandler(new GenrePanel.ImportHandler());
        
    }

    private void loadGenresFromDatabase()  {
        try {
            List<Genre> dbGenres = genreRepository.selectGenres();            
            allGenres.clear();
            allGenres.addAll(dbGenres);
            loadAllGenresModel();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Failed to load genres from database.");
        }
    }

    private void loadOrParseMovies()  {
        try {
            movieRepository = RepositoryFactory.getMovieRepository();
            
            List<Movie> dbMovies = movieRepository.selectMovies();
            if (dbMovies.isEmpty()) {
                List<Movie> parsedMovies = MovieParser.parse();
                movieRepository.createMovies(parsedMovies);
                dbMovies = parsedMovies;
            }
            
            movies.clear();
            movies.addAll(dbMovies);
            loadMoviesModel();
        } catch (Exception ex) {
                    Logger.getLogger(GenrePanel.class.getName()).log(Level.SEVERE, null, ex);
                     JOptionPane.showMessageDialog(this, "Failed to load or parse movies.");
        }
    }

