    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
         Movie selectedMovie = lsMovies.getSelectedValue();
         Genre selectedGenre = lsGenres.getSelectedValue();
         
         if (selectedMovie == null || selectedGenre == null) {
        JOptionPane.showMessageDialog(this, "Please select both a movie and a genre.");
        return;
         }
         try {
        movieRepository.updateMovieGenre(selectedMovie.getId(), selectedGenre.getId());

        
        JOptionPane.showMessageDialog(this, "Genre successfully assigned to movie!");

    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Failed to assign genre to movie.");
    }
    }//GEN-LAST:event_btnAddActionPerformed

