    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       if (selectedMovie == null) {
        MessageUtils.showInformationMessage("Wrong operation", "Please choose a movie to delete.");
        return;
    }

    if (MessageUtils.showConfirmDialog(
            "Delete movie",
            "Do you really want to delete this movie?")) {
        try {
            // Delete movie poster image if exists
            if (selectedMovie.getPicturePath() != null) {
                Files.deleteIfExists(Paths.get(selectedMovie.getPicturePath()));
            }

            // Delete actor associations (optional but clean)
            for (int actorId : movieRepository.getMovieActorIds(selectedMovie.getId())) {
                movieRepository.removeActorFromMovie(selectedMovie.getId(), actorId);
            }

            // Delete the movie itself
            movieRepository.deleteMovie(selectedMovie.getId());

            // Refresh table and reset form
            movieTableModel.setMovies(movieRepository.selectMovies());
            clearForm();

        } catch (Exception ex) {
            Logger.getLogger(EditMoviesPanel.class.getName()).log(Level.SEVERE, null, ex);
            MessageUtils.showErrorMessage("Error", "Unable to delete movie!");
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

