    private void handleEditMenu() {
        ActionMap actionMap = tpContent.getActionMap();

        menuEdit.add(createItem(
                actionMap.get(DefaultEditorKit.cutAction),
                "Cut",
                KeyStroke.getKeyStroke(KeyEvent.VK_X,
                        InputEvent.CTRL_DOWN_MASK))
        );
        menuEdit.add(createItem(
                actionMap.get(DefaultEditorKit.copyAction),
                "Copy",
                KeyStroke.getKeyStroke(KeyEvent.VK_C,
                        InputEvent.CTRL_DOWN_MASK))
        );
        menuEdit.add(createItem(
                actionMap.get(DefaultEditorKit.pasteAction),
                "Paste",
                KeyStroke.getKeyStroke(KeyEvent.VK_V,
                        InputEvent.CTRL_DOWN_MASK))
        );
        menuEdit.addSeparator();
        menuEdit.add(createItem(
                actionMap.get(DefaultEditorKit.selectAllAction),
                "Select all",
                KeyStroke.getKeyStroke(KeyEvent.VK_A,
                        InputEvent.CTRL_DOWN_MASK))
        );

    }

    private JMenuItem createItem(Action action, String text, KeyStroke acc) {

        JMenuItem mi = new JMenuItem();
        mi.setAction(action);
        mi.setText(text);
        mi.setAccelerator(acc);
        return mi;
    }

    private void handleLookAndFeelMenu() {

        ButtonGroup bg = new ButtonGroup();
        Arrays.asList(UIManager.getInstalledLookAndFeels()).forEach(info -> {
            JRadioButtonMenuItem mi = new JRadioButtonMenuItem(info.getName());
            bg.add(mi);
            menuLF.add(mi);
            mi.setSelected("Nimbus".equals(info.getName()));
            mi.addActionListener(e -> {
                try {
                    UIManager.setLookAndFeel(info.getClassName());
                    SwingUtilities.updateComponentTreeUI(MovieManager.this);
                } catch (Exception ex) {
                    Logger.getLogger(MovieManager.class.getName()).log(Level.SEVERE, null, ex);
                }
            });

        });
    }

