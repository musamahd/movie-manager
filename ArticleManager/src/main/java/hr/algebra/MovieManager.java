    private void configurePanels() {

        tpContent.removeAll();

        UserPanel userPanel;
        userPanel = new UserPanel();
       
       
        if(loggedInUser != null && loggedInUser.getRole()==Role.ADMIN)
        {
        tpContent.add(UPLOAD_MOVIES, new UploadMoviesPanel());
        tpContent.add(EDIT_MOVIES, new EditMoviesPanel());
        tpContent.add(ACTOR_PANEL, actorPanel);
        tpContent.add(DIRECTOR_PANEL, directorPanel);
        tpContent.add(GENRE_PANEL, genrePanel);
        tpContent.add(USER_PANEL,userPanel);
        } 
        else{
        tpContent.add(UPLOAD_MOVIES, new UploadMoviesPanel());
        tpContent.add(EDIT_MOVIES, new EditMoviesPanel());
         tpContent.add(USER_PANEL,userPanel);
        }

    }
